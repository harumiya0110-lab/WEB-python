let nextCatalogOrder = 0

function template(
  definition: Omit<
    ProjectTemplate,
    | 'createdAt'
    | 'sortOrder'
    | 'files'
    | 'title'
    | 'tags'
    | 'featured'
    | 'directories'
    | 'activeFile'
    | 'requiredLibraries'
    | 'availability'
  > & {
    code: string
    additionalFiles?: Record<string, string>
    directories?: string[]
    tags?: string[]
  },
): ProjectTemplate {
  const { code, additionalFiles = {}, directories = [], tags = [], ...metadata } = definition
  const files = {
    'main.py': `# ${metadata.whatYouCanDo}\n${code}`,
    ...additionalFiles,
  }
  const fileDirectories = Object.keys(files).flatMap((path) => {
    const parts = path.split('/')
    return parts.slice(0, -1).map((_, index) => parts.slice(0, index + 1).join('/'))
  })
  return {
    ...metadata,
    title: metadata.name,
    tags: [...new Set([
      metadata.name,
      metadata.category,
      metadata.difficulty,
      ...tags,
      ...metadata.learningPoints,
      ...metadata.libraries.map(({ name }) => name),
    ])],
    featured: metadata.recommended,
    sortOrder: nextCatalogOrder++,
    files,
    directories: [...new Set([...directories, ...fileDirectories])].sort(),
    activeFile: files['main.py'] ? 'main.py' : Object.keys(files).find((path) => path.endsWith('.py')) ?? Object.keys(files)[0] ?? '',
    requiredLibraries: metadata.libraries,
    availability: metadata.libraries.some(({ support }) => support === 'Pyodideで自動読み込み')
      ? 'requires-pyodide-packages'
      : 'available',
  }
}

